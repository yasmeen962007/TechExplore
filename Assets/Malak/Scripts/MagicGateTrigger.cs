    private bool canEnter = false; // ?? ??????? ????? ??????

    // ????? ???????
    public void EnableGate()
    {
        magicGateObject.SetActive(true);
        canEnter = true;
    }

    private void OnTriggerEnter(Collider other)
    {
        if (canEnter && other.CompareTag("Player"))
